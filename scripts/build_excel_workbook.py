"""Builds bi/excel/AP_business_case.xlsx: the business case as a live Excel model (Control, task 6.2).

Every result is an Excel formula fed by the Inputs sheet, so a CFO can change an
assumption or switch the scenario and see NPV, ROI and payback move. The model
mirrors src/business_case.py; the Checks sheet compares the workbook with the
Python figures (written in as fixed values) and shows OK or CHECK.

The measured € inputs are the analysis results (12 months to 31 August 2026),
written as values with their source, never re-derived in Excel. Pivot tables
and the Power Query import of bi/data/*.csv are added in Excel itself, from the
guide in bi/excel/README.md: openpyxl can't create them.

Conventions: blue = input, black = formula, green = link to another sheet,
yellow fill = the scenario switch. Arial throughout.

Run: python scripts/build_excel_workbook.py bi/excel/AP_business_case.xlsx
"""

import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.chart import BarChart, Reference
from openpyxl.comments import Comment
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.workbook.defined_name import DefinedName
from openpyxl.worksheet.datavalidation import DataValidation

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import business_case as bc  # noqa: E402
from src import impact  # noqa: E402

BLUE, GREEN, BLACK, GREY = "0000FF", "008000", "000000", "595959"
EUR = '"€"#,##0;("€"#,##0);"-"'
EUR2 = '"€"#,##0.00;("€"#,##0.00);"-"'
PCT = "0.0%"
DAYS = "0"
FONT = "Arial"
HEADER_FILL = PatternFill("solid", fgColor="DCE6F2")
SWITCH_FILL = PatternFill("solid", fgColor="FFFF00")
THIN = Side(style="thin", color="BFBFBF")

# Assumption key → Excel name. Percent-points in Python become fractions here.
ASSUMPTION_NAMES = {
    "duplicate_prevention": "Eff_Duplicates",
    "pay_to_terms": "Eff_PayToTerms",
    "approval_deadline": "Eff_Approval",
    "entry_validation": "Eff_EntryValidation",
    "po_compliance": "Eff_POCompliance",
    "duplicate_recovery_rate": "Recovery_Rate",
    "po_premium_pct": "PO_Premium",
    "cost_multiplier": "Cost_Multiplier",
    "cost_of_capital_pct": "CoC",
    "ramp_up_year_1": "Ramp_Y1",
}
PERCENT_POINTS = {"po_premium_pct", "cost_of_capital_pct"}

LEVER_EFFECT = {  # lever effectiveness key → Excel name
    key: name for key, name in ASSUMPTION_NAMES.items()
    if key in {"duplicate_prevention", "pay_to_terms", "approval_deadline", "entry_validation", "po_compliance"}
}


def style(cell, color=BLACK, fmt=None, bold=False, fill=None, wrap=False):
    cell.font = Font(name=FONT, size=10, color=color, bold=bold)
    if fmt:
        cell.number_format = fmt
    if fill:
        cell.fill = fill
    if wrap:
        cell.alignment = Alignment(wrap_text=True, vertical="top")


def header(ws, row, labels, widths=None):
    for col, label in enumerate(labels, start=1):
        cell = ws.cell(row=row, column=col, value=label)
        style(cell, bold=True, fill=HEADER_FILL, wrap=True)
        cell.border = Border(bottom=THIN)
    if widths:
        for col, width in enumerate(widths, start=1):
            ws.column_dimensions[chr(64 + col)].width = width


def name(wb, label, ref):
    wb.defined_names[label] = DefinedName(label, attr_text=ref)


def scenario_value(key: str, scenario: str, data_based: dict) -> float:
    value = bc.ASSUMPTIONS[key][scenario]
    value = data_based[key] if value is None else value
    return value / 100 if key in PERCENT_POINTS else value


def build(path: Path) -> None:
    case = bc.compute_business_case()
    measured, data_based, base = case["measured"], case["data_based"], case["base"]
    wb = Workbook()

    # --- README ---------------------------------------------------------------------
    ws = wb.active
    ws.title = "README"
    ws.column_dimensions["A"].width = 110
    lines = [
        ("AP Spend Leakage Analyzer: business case model (Rheinwerk Komponenten GmbH, fictional client)", True),
        ("Generated by scripts/build_excel_workbook.py from the same figures as the app. All data is synthetic.", False),
        ("", False),
        ("How to use", True),
        ("1. Inputs: pick Worst, Base or Best in the yellow cell, or change any blue value.", False),
        ("2. Levers, Cash flow and Scenarios recalculate: NPV, ROI and payback are formulas, not pasted values.", False),
        ("3. Sensitivity moves one assumption at a time to its worst and best value (tornado chart).", False),
        ("4. Checks compares the workbook with the Python model; every row shows OK in the Base scenario.", False),
        ("", False),
        ("Colour code", True),
        ("Blue text: input or assumption you may change. Black: formula. Green: link to another sheet.", False),
        ("Yellow fill: the scenario switch.", False),
        ("", False),
        ("Rules kept from the analysis", True),
        ("Hard benefits (cash) and estimated savings are never added into one headline: the NPV is shown for both.", False),
        ("AP time saved by less rework is not counted as a benefit; staff time is counted as a cost (conservative).", False),
        ("", False),
        ("Pivot tables and Power Query: see bi/excel/README.md (built in Excel from bi/data/*.csv).", False),
    ]
    for row, (text, bold) in enumerate(lines, start=1):
        style(ws.cell(row=row, column=1, value=text), bold=bold)

    # --- Inputs ---------------------------------------------------------------------
    ws = wb.create_sheet("Inputs")
    style(ws.cell(row=1, column=1, value="Scenario"), bold=True)
    switch = ws.cell(row=1, column=2, value="Base")
    style(switch, color=BLUE, bold=True, fill=SWITCH_FILL)
    validation = DataValidation(type="list", formula1='"Worst,Base,Best"', allow_blank=False)
    ws.add_data_validation(validation)
    validation.add("B1")
    style(ws.cell(row=1, column=3, value="Worst, Base or Best: drives the Active column below"), color=GREY)
    name(wb, "Scenario", "Inputs!$B$1")
    ws.cell(row=2, column=1, value="Scenario index")
    ws.cell(row=2, column=2, value='=MATCH(Scenario,{"Worst","Base","Best"},0)')
    style(ws.cell(row=2, column=1)); style(ws.cell(row=2, column=2))
    name(wb, "Scenario_Index", "Inputs!$B$2")

    header(ws, 4, ["Assumption", "Worst", "Base", "Best", "Active", "Name", "Source"],
           [56, 13, 11, 11, 11, 20, 70])
    row = 5
    for key, excel_name in ASSUMPTION_NAMES.items():
        spec = bc.ASSUMPTIONS[key]
        style(ws.cell(row=row, column=1, value=spec["label"]))
        fmt = "0.00x" if key == "cost_multiplier" else PCT
        for col, scenario in zip([2, 3, 4], ["worst", "base", "best"]):
            style(ws.cell(row=row, column=col, value=scenario_value(key, scenario, data_based)), BLUE, fmt)
        style(ws.cell(row=row, column=5, value=f"=INDEX(B{row}:D{row},Scenario_Index)"), BLACK, fmt)
        style(ws.cell(row=row, column=6, value=excel_name), GREY)
        style(ws.cell(row=row, column=7, value=spec["source"]), GREY)
        name(wb, excel_name, f"Inputs!$E${row}")
        for col, scenario in zip([2, 3, 4], ["Worst", "Base", "Best"]):
            name(wb, f"{excel_name}_{scenario}", f"Inputs!${'BCD'[col - 2]}${row}")
        row += 1

    row += 1
    header(ws, row, ["Measured figure (12 months to 31 Aug 2026)", "€ a year", "", "", "", "Name", "Source"])
    row += 1
    pareto = case["measured"]
    no_po_spend = measured["Purchase-order premium"] / (impact.PO_PREMIUM_PCT / 100)
    figures = [
        ("Duplicate payments (no duplicate check at entry)", pareto[bc.root_cause.NO_DUPLICATE_CHECK],
         "M_Duplicates", "src/root_cause.py, leakage by cause"),
        ("Payment run ignores discount and due dates", pareto[bc.root_cause.PAYMENT_RUN_IGNORES_TERMS],
         "M_PaymentRun", "src/root_cause.py, leakage by cause"),
        ("Slow approval, no rework", pareto[bc.root_cause.SLOW_APPROVAL], "M_SlowApproval",
         "src/root_cause.py, leakage by cause"),
        ("Rework delays approval past the deadline", pareto[bc.root_cause.REWORK_DELAYS_APPROVAL], "M_Rework",
         "src/root_cause.py, leakage by cause"),
        ("Duplicates already paid (one-off claim-back base)", measured["paid_duplicates"], "M_PaidDuplicates",
         "src/impact.py, duplicate copies already paid"),
        ("Spend without a purchase order", no_po_spend, "M_NoPOSpend", "src/kpis.py, no-PO invoice spend"),
        ("Working capital given away, at the Measure cost of capital", measured["Working capital given away"],
         "M_WorkingCapital", "src/impact.py, early-payment cost"),
        ("Cost of capital used in Measure", impact.COST_OF_CAPITAL_PCT / 100, "M_CoC_Measure",
         "src/impact.py; working capital € scales with the Active cost of capital"),
    ]
    for label, value, excel_name, source in figures:
        style(ws.cell(row=row, column=1, value=label))
        style(ws.cell(row=row, column=2, value=round(value, 2)), BLUE, PCT if excel_name == "M_CoC_Measure" else EUR2)
        style(ws.cell(row=row, column=6, value=excel_name), GREY)
        style(ws.cell(row=row, column=7, value=source), GREY)
        name(wb, excel_name, f"Inputs!$B${row}")
        row += 1

    row += 1
    header(ws, row, ["Cost rate", "€ a day", "", "", "", "Name", "Source"])
    row += 1
    for label, value, excel_name, source in [
        ("IT day rate (external SAP consultant)", bc.IT_DAY_RATE_EUR, "Rate_IT", "Consultant estimate; confirm with IT"),
        ("Internal day rate (AP or Procurement staff, fully loaded)", bc.INTERNAL_DAY_RATE_EUR, "Rate_Internal",
         "About €50 an hour; confirm with HR controlling"),
    ]:
        style(ws.cell(row=row, column=1, value=label))
        style(ws.cell(row=row, column=2, value=value), BLUE, EUR)
        style(ws.cell(row=row, column=6, value=excel_name), GREY)
        style(ws.cell(row=row, column=7, value=source), GREY)
        name(wb, excel_name, f"Inputs!$B${row}")
        row += 1

    # --- Levers ---------------------------------------------------------------------
    ws = wb.create_sheet("Levers")
    header(ws, 1, ["Fix", "Benefit type", "€ a year at stake", "Removed", "€ benefit a year", "IT days",
                   "Business days", "One-off cost at estimate", "One-off cost", "Run days a year",
                   "Running cost a year", "Owner"],
           [36, 16, 15, 10, 15, 9, 10, 15, 13, 10, 15, 30])
    at_stake = {
        bc.root_cause.NO_DUPLICATE_CHECK: "=M_Duplicates",
        bc.root_cause.PAYMENT_RUN_IGNORES_TERMS: "=M_PaymentRun",
        bc.root_cause.SLOW_APPROVAL: "=M_SlowApproval",
        bc.root_cause.REWORK_DELAYS_APPROVAL: "=M_Rework",
        "Purchase-order premium": "=M_NoPOSpend*PO_Premium",
        "Working capital given away": "=M_WorkingCapital*CoC/M_CoC_Measure",
    }
    first = 2
    for i, lever in enumerate(bc.LEVERS):
        r = first + i
        style(ws.cell(row=r, column=1, value=lever["lever"]))
        style(ws.cell(row=r, column=2, value=lever["benefit_type"]))
        stake = at_stake.get(lever["addresses"], 0)
        style(ws.cell(row=r, column=3, value=stake), GREEN if stake else BLACK, EUR)
        effect = f"={LEVER_EFFECT[lever['effectiveness']]}" if lever["effectiveness"] else 0
        style(ws.cell(row=r, column=4, value=effect), GREEN if effect else BLACK, PCT)
        style(ws.cell(row=r, column=5, value=f"=C{r}*D{r}"), BLACK, EUR)
        style(ws.cell(row=r, column=6, value=lever["cost_it_days"]), BLUE, DAYS)
        style(ws.cell(row=r, column=7, value=lever["cost_business_days"]), BLUE, DAYS)
        style(ws.cell(row=r, column=8, value=f"=F{r}*Rate_IT+G{r}*Rate_Internal"), BLACK, EUR)
        style(ws.cell(row=r, column=9, value=f"=H{r}*Cost_Multiplier"), BLACK, EUR)
        style(ws.cell(row=r, column=10, value=lever["run_business_days"]), BLUE, DAYS)
        style(ws.cell(row=r, column=11, value=f"=J{r}*Rate_Internal*Cost_Multiplier"), BLACK, EUR)
        style(ws.cell(row=r, column=12, value=lever["owner"]), GREY)
    last = first + len(bc.LEVERS) - 1
    total = last + 2
    totals = [
        ("Hard benefit a year", f'=SUMIF(B{first}:B{last},"{bc.HARD}",E{first}:E{last})', "Hard_Benefit"),
        ("Estimated saving a year", f'=SUMIF(B{first}:B{last},"{bc.ESTIMATED}",E{first}:E{last})', "Estimated_Saving"),
        ("One-off investment", f"=SUM(I{first}:I{last})", "Investment"),
        ("One-off investment at estimate", f"=SUM(H{first}:H{last})", "Investment_Estimate"),
        ("Running cost a year", f"=SUM(K{first}:K{last})", "Run_Cost"),
        ("Running cost a year at estimate", f"=SUMPRODUCT(J{first}:J{last})*Rate_Internal", "Run_Cost_Estimate"),
    ]
    for i, (label, formula, excel_name) in enumerate(totals):
        r = total + i
        style(ws.cell(row=r, column=1, value=label), bold=True)
        style(ws.cell(row=r, column=5, value=formula), BLACK, EUR, bold=True)
        name(wb, excel_name, f"Levers!$E${r}")

    # --- Cash flow ------------------------------------------------------------------
    ws = wb.create_sheet("Cash flow")
    ws.column_dimensions["A"].width = 40
    for col in "BCDE":
        ws.column_dimensions[col].width = 14

    def cash_block(top: int, title: str, benefit: str, prefix: str):
        style(ws.cell(row=top, column=1, value=title), bold=True)
        header_row = top + 1
        for col, year in enumerate(range(bc.YEARS + 1), start=2):
            c = ws.cell(row=header_row, column=col, value=f"Year {year}")
            style(c, bold=True, fill=HEADER_FILL)
        style(ws.cell(row=header_row, column=1, value="€"), bold=True, fill=HEADER_FILL)
        labels = ["Benefit", "Duplicates recovered (one-off)", "Cost", "Net cash flow", "Discount factor",
                  "Discounted", "Running total"]
        rows = {label: header_row + 1 + i for i, label in enumerate(labels)}
        for label, r in rows.items():
            style(ws.cell(row=r, column=1, value=label), bold=label in ("Net cash flow",))
        for col in range(2, 6):
            year = col - 2
            letter = chr(64 + col)
            prev = chr(63 + col)
            benefit_formula = "=0" if year == 0 else (f"={benefit}*Ramp_Y1" if year == 1 else f"={benefit}")
            style(ws.cell(row=rows["Benefit"], column=col, value=benefit_formula), BLACK, EUR)
            recovery = "=M_PaidDuplicates*Recovery_Rate" if year == 1 else "=0"
            style(ws.cell(row=rows["Duplicates recovered (one-off)"], column=col, value=recovery), BLACK, EUR)
            style(ws.cell(row=rows["Cost"], column=col, value="=-Investment" if year == 0 else "=-Run_Cost"), BLACK, EUR)
            net = f"=SUM({letter}{rows['Benefit']}:{letter}{rows['Cost']})"
            style(ws.cell(row=rows["Net cash flow"], column=col, value=net), BLACK, EUR, bold=True)
            style(ws.cell(row=rows["Discount factor"], column=col, value=f"=1/(1+CoC)^{year}"), BLACK, "0.0000")
            style(ws.cell(row=rows["Discounted"], column=col,
                          value=f"={letter}{rows['Net cash flow']}*{letter}{rows['Discount factor']}"), BLACK, EUR)
            running = (f"={letter}{rows['Net cash flow']}" if year == 0
                       else f"={prev}{rows['Running total']}+{letter}{rows['Net cash flow']}")
            style(ws.cell(row=rows["Running total"], column=col, value=running), BLACK, EUR)
        net, run = rows["Net cash flow"], rows["Running total"]
        results = [
            ("NPV (3 years)", f"=SUM(B{rows['Discounted']}:E{rows['Discounted']})", EUR, f"{prefix}_NPV"),
            ("ROI (3 years)", f"=(SUM(C{net}:E{net})+B{net})/-B{net}", PCT, f"{prefix}_ROI"),
            ("Payback (months)",
             f'=IF(C{run}>=0,-B{run}/C{net}*12,IF(D{run}>=0,12-C{run}/D{net}*12,'
             f'IF(E{run}>=0,24-D{run}/E{net}*12,"Not within 3 years")))', "0.0", f"{prefix}_Payback"),
        ]
        r = rows["Running total"] + 2
        for label, formula, fmt, excel_name in results:
            style(ws.cell(row=r, column=1, value=label), bold=True)
            style(ws.cell(row=r, column=2, value=formula), BLACK, fmt, bold=True)
            name(wb, excel_name, f"'Cash flow'!$B${r}")
            r += 1
        return r

    next_top = cash_block(1, "Hard benefits only (the headline)", "Hard_Benefit", "Hard")
    cash_block(next_top + 1, "Including estimated savings (never the headline)", "(Hard_Benefit+Estimated_Saving)",
               "WithEstimated")

    # --- Scenarios ------------------------------------------------------------------
    # The same model in closed form, once per scenario, reading the Worst/Base/Best
    # columns directly, so the three cases sit side by side whatever the switch says.
    ws = wb.create_sheet("Scenarios")
    ws.column_dimensions["A"].width = 42
    for col in "BCD":
        ws.column_dimensions[col].width = 15
    header(ws, 1, ["€", "Worst", "Base", "Best"])
    labels = ["Hard benefit a year", "Estimated saving a year", "Investment", "Running cost a year",
              "Net cash flow, year 1", "Net cash flow, years 2 and 3", "NPV, hard benefits", "ROI, hard benefits",
              "Payback (months)", "NPV without the one-off claim-back", "NPV including estimated savings"]
    rows = {label: 2 + i for i, label in enumerate(labels)}
    for label, r in rows.items():
        style(ws.cell(row=r, column=1, value=label), bold=label.startswith("NPV"))
    for col, scen in zip("BCD", ["Worst", "Base", "Best"]):
        n = lambda key: f"{ASSUMPTION_NAMES[key]}_{scen}"  # noqa: E731
        hard = (f"=M_Duplicates*{n('duplicate_prevention')}+M_PaymentRun*{n('pay_to_terms')}"
                f"+M_SlowApproval*{n('approval_deadline')}+M_Rework*{n('entry_validation')}")
        est = (f"=M_NoPOSpend*{n('po_premium_pct')}*{n('po_compliance')}"
               f"+M_WorkingCapital*{n('cost_of_capital_pct')}/M_CoC_Measure*{n('pay_to_terms')}")
        r = rows
        rate = n("cost_of_capital_pct")
        formulas = {
            "Hard benefit a year": (hard, EUR),
            "Estimated saving a year": (est, EUR),
            "Investment": (f"=Investment_Estimate*{n('cost_multiplier')}", EUR),
            "Running cost a year": (f"=Run_Cost_Estimate*{n('cost_multiplier')}", EUR),
            "Net cash flow, year 1": (f"={col}{r['Hard benefit a year']}*{n('ramp_up_year_1')}"
                                      f"+M_PaidDuplicates*{n('duplicate_recovery_rate')}-{col}{r['Running cost a year']}", EUR),
            "Net cash flow, years 2 and 3": (f"={col}{r['Hard benefit a year']}-{col}{r['Running cost a year']}", EUR),
            "NPV, hard benefits": (f"=-{col}{r['Investment']}+{col}{r['Net cash flow, year 1']}/(1+{rate})"
                                   f"+{col}{r['Net cash flow, years 2 and 3']}*(1/(1+{rate})^2+1/(1+{rate})^3)", EUR),
            "ROI, hard benefits": (f"=({col}{r['Net cash flow, year 1']}+2*{col}{r['Net cash flow, years 2 and 3']}"
                                   f"-{col}{r['Investment']})/{col}{r['Investment']}", PCT),
            "Payback (months)": (f"=IF({col}{r['Net cash flow, year 1']}>={col}{r['Investment']},"
                                 f"{col}{r['Investment']}/{col}{r['Net cash flow, year 1']}*12,"
                                 f"12+({col}{r['Investment']}-{col}{r['Net cash flow, year 1']})"
                                 f"/{col}{r['Net cash flow, years 2 and 3']}*12)", "0.0"),
            "NPV without the one-off claim-back": (
                f"={col}{r['NPV, hard benefits']}-M_PaidDuplicates*{n('duplicate_recovery_rate')}/(1+{rate})", EUR),
            "NPV including estimated savings": (
                f"={col}{r['NPV, hard benefits']}+{col}{r['Estimated saving a year']}*({n('ramp_up_year_1')}/(1+{rate})"
                f"+1/(1+{rate})^2+1/(1+{rate})^3)", EUR),
        }
        for label, (formula, fmt) in formulas.items():
            style(ws.cell(row=r[label], column="BCD".index(col) + 2, value=formula), BLACK, fmt,
                  bold=label.startswith("NPV"))
    note = ws.cell(row=rows["NPV including estimated savings"] + 2, column=1,
                   value="Payback assumes it falls within years 1–2, as in every case here; the Cash flow sheet "
                         "computes it year by year.")
    style(note, GREY)

    # --- Sensitivity ----------------------------------------------------------------
    ws = wb.create_sheet("Sensitivity")
    params = ["duplicate_prevention", "pay_to_terms", "approval_deadline", "entry_validation",
              "duplicate_recovery_rate", "cost_multiplier", "cost_of_capital_pct", "ramp_up_year_1"]
    labels = ["Assumption", "Set to"] + [bc.ASSUMPTIONS[p]["label"] for p in params] + [
        "Hard benefit", "Investment", "Running cost", "Year 1 net", "Years 2–3 net", "NPV, hard benefits"]
    header(ws, 1, labels, [32, 13] + [12] * len(params) + [13, 12, 12, 12, 12, 15])
    ws.row_dimensions[1].height = 45
    order = list(case["tornado"]["assumption"])  # largest swing first, as in the app
    key_by_label = {bc.ASSUMPTIONS[k]["label"]: k for k in params}
    order = [label for label in order if label in key_by_label]
    r = 2
    grid_rows = {}
    for label in order:
        key = key_by_label[label]
        for side in ["Worst", "Best"]:
            style(ws.cell(row=r, column=1, value=label))
            style(ws.cell(row=r, column=2, value=side))
            for j, p in enumerate(params):
                ref = f"={ASSUMPTION_NAMES[p]}_{side if p == key else 'Base'}"
                fmt = "0.00x" if p == "cost_multiplier" else PCT
                style(ws.cell(row=r, column=3 + j, value=ref), GREEN, fmt)
            c = {p: f"{chr(67 + j)}{r}" for j, p in enumerate(params)}
            k0 = 3 + len(params)
            col = lambda i: chr(64 + k0 + i)  # noqa: E731
            cells = [
                (f"=M_Duplicates*{c['duplicate_prevention']}+M_PaymentRun*{c['pay_to_terms']}"
                 f"+M_SlowApproval*{c['approval_deadline']}+M_Rework*{c['entry_validation']}", EUR),
                (f"=Investment_Estimate*{c['cost_multiplier']}", EUR),
                (f"=Run_Cost_Estimate*{c['cost_multiplier']}", EUR),
                (f"={col(0)}{r}*{c['ramp_up_year_1']}+M_PaidDuplicates*{c['duplicate_recovery_rate']}-{col(2)}{r}", EUR),
                (f"={col(0)}{r}-{col(2)}{r}", EUR),
                (f"=-{col(1)}{r}+{col(3)}{r}/(1+{c['cost_of_capital_pct']})+{col(4)}{r}"
                 f"*(1/(1+{c['cost_of_capital_pct']})^2+1/(1+{c['cost_of_capital_pct']})^3)", EUR),
            ]
            for i, (formula, fmt) in enumerate(cells):
                style(ws.cell(row=r, column=k0 + i, value=formula), BLACK, fmt)
            grid_rows[(label, side)] = (r, col(5))
            r += 1
    # Tornado summary and chart.
    top = r + 2
    style(ws.cell(row=top - 1, column=1, value="Tornado: NPV with one assumption at its worst and best value"),
          bold=True)
    for col, text in enumerate(["Assumption", "NPV at worst", "NPV at best", "Swing"], start=1):
        style(ws.cell(row=top, column=col, value=text), bold=True, fill=HEADER_FILL)
    for i, label in enumerate(order):
        rr = top + 1 + i
        worst_r, npv_col = grid_rows[(label, "Worst")]
